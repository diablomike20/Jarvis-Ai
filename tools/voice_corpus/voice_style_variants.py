#!/usr/bin/env python3
"""Produce NON-AUTHENTICATED candidate JARVIS-style effects from a generated TTS WAV.

Presets are *experiments*, never claims of recreating the actual movie mix.
All inputs and outputs stay local/outside the GitHub repository.
Uses ffmpeg on existing PCM WAV outputs of F5 / XTTS voice lab.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys
import wave

REPO_ROOT = Path(__file__).resolve().parents[2]
PRESETS = {
    # Baseline: same recording converted to a standardized, unprocessed PCM16 WAV
    "natural": "anull",
    # Film-inspired restraint: remove rumble, preserve fundamental speech, light
    # high-frequency detail and controlled dynamic range.
    "jarvis_subtle": (
        "highpass=f=95,lowpass=f=9000,"
        "equalizer=f=3000:t=q:w=1.2:g=1.7,"
        "acompressor=threshold=0.20:ratio=1.5:attack=12:release=120:makeup=1"
    ),
    # Clearly separate communication/HUD effect, not an authenticity reference.
    "jarvis_comms": (
        "highpass=f=185,lowpass=f=4700,"
        "equalizer=f=2400:t=q:w=0.9:g=2.0,"
        "acompressor=threshold=0.16:ratio=2.1:attack=6:release=100:makeup=1"
    ),
}


def private_path(value: str) -> Path:
    path = Path(value).expanduser().resolve()
    if path == REPO_ROOT or path.is_relative_to(REPO_ROOT):
        raise ValueError("Private voice audio cannot be stored inside Git repository.")
    return path


def digest(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1048576), b""):
            h.update(chunk)
    return h.hexdigest()


def wav_info(path: Path) -> dict:
    with wave.open(str(path), "rb") as w:
        if w.getnframes() <= 0 or w.getframerate() <= 0:
            raise ValueError("WAV is empty or invalid")
        return {"channels": w.getnchannels(),
                "sample_rate": w.getframerate(),
                "sample_width": w.getsampwidth(),
                "duration_s": round(w.getnframes() / w.getframerate(), 4)}


def process(input_wav: Path, output_dir: Path, *, presets=None, dry_run=False) -> dict:
    source = private_path(str(input_wav))
    target = private_path(str(output_dir))
    if not source.is_file() or source.suffix.lower() != ".wav":
        raise ValueError("Need existing local WAV generated by F5/XTTS.")
    if source == target or target.is_relative_to(source):
        raise ValueError("Output must differ from input.")
    if target.exists():
        raise FileExistsError(f"Refusing to overwrite existing output: {target}")
    if source.stat().st_size <= 44:
        raise ValueError("Input WAV too short.")
    info = wav_info(source)
    variants = list(PRESETS) if presets is None else list(presets)
    if not variants or any(p not in PRESETS for p in variants) or len(set(variants)) != len(variants):
        raise ValueError("Unknown/duplicate/empty preset.")
    executable = shutil.which("ffmpeg")
    if not executable and not dry_run:
        raise RuntimeError("ffmpeg not available on PATH.")
    report = {"input": source.name, "input_sha256": digest(source),
              "input_info": info, "authentic_movie_filter": False,
              "verified_human_voice": False,
              "warning": "These are optional processing variants, NOT the film's original JARVIS effects.",
              "variants": []}
    if not dry_run:
        target.mkdir(parents=True, exist_ok=False)
    for preset in variants:
        output = target / f"{source.stem}__{preset}.wav"
        argv = [executable or "ffmpeg", "-hide_banner", "-loglevel", "error",
                "-nostdin", "-n", "-i", str(source), "-vn", "-af", PRESETS[preset],
                "-c:a", "pcm_s16le", str(output)]
        if dry_run:
            report["variants"].append({"preset": preset, "status": "dry_run",
                                       "filter_graph": PRESETS[preset]})
            continue
        done = subprocess.run(argv, capture_output=True, text=True,
                              timeout=300, encoding="utf-8", errors="replace")
        if done.returncode:
            report["variants"].append({"preset": preset, "status": "ffmpeg_error",
                                       "error": done.stderr[-750:]})
            continue
        stats = wav_info(output)
        report["variants"].append(
            {"preset": preset, "status": "generated_unreviewed",
             "wav_file": output.name, "sha256": digest(output),
             "audio": stats, "filter_graph": PRESETS[preset]})
    if not dry_run:
        (target / "variant_manifest.json").write_text(
            json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    return report


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--input", required=True)
    p.add_argument("--output-dir", required=True)
    p.add_argument("--presets", nargs="+", choices=list(PRESETS))
    p.add_argument("--dry-run", action="store_true")
    args = p.parse_args()
    try:
        result = process(Path(args.input), Path(args.output_dir),
                         presets=args.presets, dry_run=args.dry_run)
        print(json.dumps(result, ensure_ascii=False, indent=2))
        if not args.dry_run and not any(
            row["status"] == "generated_unreviewed" for row in result["variants"]
        ):
            raise SystemExit(1)
    except (RuntimeError, ValueError, OSError, subprocess.TimeoutExpired) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        raise SystemExit(2) from exc


if __name__ == "__main__":
    main()
